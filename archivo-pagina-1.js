//operadores de asignacion incremento y decremento

let a = 1;

document.write('valor de a:', a);
document.write('<br>');
a++; // aquí asi realizamos el aumento de valor de a en 1 
document.write('valor de a:', a);
document.write('<br>');
a+=5;//aumento variable dependiendo el valor que le de conocido como valor de incremento 
document.write('valor de a:', a);
document.write('<br>');
a--;//resta valor en uno a nuestra variable 
document.write('valor de a:', a);
document.write('<br>');
a-=3;// reduce variable dependiendo el valor que le de conocido como valor de decremento
document.write('valor de a:', a);
document.write('<br>');
a*=4;//este multiplica mi variable a por el valor que le demos
document.write('valor de a:', a);
document.write('<br>');
a/=3;//esta divide a entre el valor que le demos
document.write('valor de a:', a);
document.write('<br>');
a**=2;//esta operacion nos genera potenciación en este caso a elevado a la 2 
document.write('valor de a:', a);
document.write('<br>');
//asi es como funcionan los operadores de asignación 







